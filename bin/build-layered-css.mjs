#!/usr/bin/env node
/**
 * Write a `<name>.layer.css` twin of every frontend stylesheet, wrapped in
 * `@layer listora { ... }`.
 *
 * Theme_Defenses::layer_listora_styles() links the twin on the frontend, so
 * each sheet sits in the listora cascade layer as an ordinary <link> that
 * cache plugins can combine, defer and build critical CSS from. 1.9.0 printed
 * an inline `@import ... layer(listora)` instead, which no cache plugin can
 * touch (Zoho #42047, card 10388619256). The unwrapped file stays as it is:
 * wp-admin and the block editor load it unlayered on purpose.
 *
 * Covers assets/css, assets/vendor and blocks, LTR and RTL twins alike, and
 * skips admin and editor sheets, the isolation rule (it must stay unlayered)
 * and the twins themselves. Listora Pro runs this script on its own tree.
 *
 * Usage: node bin/build-layered-css.mjs [plugin-dir] [--check]
 */

import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { dirname, resolve, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice( 2 );
const CHECK_ONLY = args.includes( '--check' );
const dirArg = args.find( ( a ) => ! a.startsWith( '--' ) );
const PLUGIN_DIR = dirArg
	? resolve( dirArg )
	: resolve( dirname( fileURLToPath( import.meta.url ) ), '..' );

// At-rules that are invalid inside a layer block; a source carrying one needs a hand decision.
const UNWRAPPABLE = /@(import|charset|layer)\b/;

function isLayeredSource( rel ) {
	const name = basename( rel );
	return (
		rel.endsWith( '.css' ) &&
		! rel.endsWith( '.layer.css' ) &&
		! /(^|\/)admin\//.test( rel ) &&
		! name.includes( 'admin' ) &&
		! name.includes( 'editor' ) &&
		! name.startsWith( 'listora-isolation' )
	);
}

const sources = [];
for ( const dir of [ 'assets/css', 'assets/vendor', 'blocks' ] ) {
	const abs = resolve( PLUGIN_DIR, dir );
	if ( ! existsSync( abs ) ) {
		continue;
	}
	for ( const entry of readdirSync( abs, { recursive: true } ) ) {
		const rel = `${ dir }/${ String( entry ).split( '\\' ).join( '/' ) }`;
		if ( isLayeredSource( rel ) ) {
			sources.push( rel );
		}
	}
}

let failed = false;
for ( const rel of sources.sort() ) {
	const twinRel = rel.replace( /\.css$/, '.layer.css' );
	const twinAbs = resolve( PLUGIN_DIR, twinRel );
	const css = readFileSync( resolve( PLUGIN_DIR, rel ), 'utf8' );
	const body = css.replace( /\/\*[\s\S]*?\*\//g, '' );
	if ( UNWRAPPABLE.test( body ) ) {
		failed = true;
		// eslint-disable-next-line no-console
		console.error( `✗ ${ rel } has @import/@charset/@layer and cannot be wrapped in a layer.` );
		continue;
	}
	const twin =
		`/* GENERATED by wb-listora/bin/build-layered-css.mjs from ${ basename( rel ) } — do NOT edit. */\n` +
		`@layer listora {\n${ css.replace( /\s+$/, '' ) }\n}\n`;
	if ( CHECK_ONLY ) {
		const existing = existsSync( twinAbs ) ? readFileSync( twinAbs, 'utf8' ) : '';
		if ( existing !== twin ) {
			failed = true;
			// eslint-disable-next-line no-console
			console.error( `✗ ${ twinRel } is stale — run \`npm run build:css\` and commit.` );
		}
	} else {
		writeFileSync( twinAbs, twin );
	}
}

// eslint-disable-next-line no-console
console.log( `${ failed ? '✗' : '✓' } ${ sources.length } layered twins ${ CHECK_ONLY ? 'checked' : 'written' } in ${ basename( PLUGIN_DIR ) }` );
process.exit( failed ? 1 : 0 );
