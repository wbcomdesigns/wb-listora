#!/usr/bin/env bash
# bin/local-ci.sh — local-CI gate for WB Listora.
#
# Single entry point that runs every quality + correctness + journey
# check in the right order. Designed to be runnable from a fresh clone
# without GitHub Actions or any external infrastructure.
#
# Usage:
#   composer ci                         # via composer script
#   bash bin/local-ci.sh                # direct, all stages
#   bash bin/local-ci.sh --no-journeys  # skip browser-dependent stages
#   bash bin/local-ci.sh --quick        # lint + coding-rules only (~10s)
#
# Exit 0 = green; non-zero = at least one stage failed (the offending
# stage's stdout/stderr was already printed). Each stage has a numeric
# tag (1.x = static, 2.x = security, 3.x = manifest, 4.x = journeys)
# so you can scroll back to the first red.
#
# Generated by wp-plugin-onboard skill. Edit freely — this is your
# plugin's CI orchestrator, not skill state.

set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PLUGIN_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
PLUGIN_SLUG="$(basename "$PLUGIN_DIR")"

cd "$PLUGIN_DIR"

MODE="full"
SITE_URL="${LOCAL_CI_SITE_URL:-http://wb-listora.local}"

while [ $# -gt 0 ]; do
  case "$1" in
    --no-journeys) MODE="no-journeys" ;;
    --quick)       MODE="quick" ;;
    --site)        SITE_URL="$2"; shift ;;
    *) echo "Unknown flag: $1"; exit 2 ;;
  esac
  shift
done

# ─── helpers ─────────────────────────────────────────────────────────────────

FAILED=()
GREEN="\033[0;32m"; RED="\033[0;31m"; YELLOW="\033[0;33m"; DIM="\033[2m"; RESET="\033[0m"

step() { printf "${DIM}[%s]${RESET} %s\n" "$1" "${@:2}"; }
pass() { printf "${GREEN}✓${RESET}  %s\n" "$*"; }
fail() { printf "${RED}✗${RESET}  %s\n" "$*"; FAILED+=("$1"); }
warn() { printf "${YELLOW}!${RESET}  %s\n" "$*"; }

run_stage() {
  local tag="$1"; local label="$2"; shift 2
  step "$tag" "$label"
  if "$@" > /tmp/local-ci-$$.log 2>&1; then
    pass "$label"
  else
    fail "$tag $label"
    cat /tmp/local-ci-$$.log | sed 's/^/    /'
  fi
  rm -f /tmp/local-ci-$$.log
}

echo "=== WB Listora local-CI ==="
echo "Mode: $MODE  ·  Site: $SITE_URL"
echo ""

# ─── 1.x — Static checks (fast, no runtime needed) ───────────────────────────

step "1.1" "PHP lint (every changed-source PHP file)"
PHP_LINT_FAILED=0
while IFS= read -r -d '' file; do
  if ! php -l "$file" > /dev/null 2>&1; then
    fail "1.1 PHP lint: $file"
    php -l "$file" 2>&1 | sed 's/^/    /'
    PHP_LINT_FAILED=1
  fi
done < <(find . -type f -name '*.php' \
          -not -path './vendor/*' \
          -not -path './node_modules/*' \
          -not -path './tests/*' \
          -not -path './build/*' \
          -not -path './dist/*' \
          -not -path './.git/*' \
          -print0)
[ "$PHP_LINT_FAILED" = "0" ] && pass "PHP lint clean"

if [ "$MODE" = "quick" ]; then
  step "QUICK" "skipping WPCS / PHPStan / wppqa / journeys"
else
  if [ -f phpcs.xml ] || [ -f .phpcs.xml.dist ]; then
    if [ -x vendor/bin/phpcs ]; then
      run_stage "1.2" "WPCS (phpcs)" composer phpcs
    else
      warn "1.2 WPCS skipped — run 'composer install' first"
    fi
  fi

  if [ -f phpstan.neon ] || [ -f phpstan.neon.dist ]; then
    if [ -x vendor/bin/phpstan ]; then
      run_stage "1.3" "PHPStan static analysis" composer phpstan
    else
      warn "1.3 PHPStan skipped — vendor/bin/phpstan not present"
    fi
  fi
fi

# 1.4 — PHPUnit. The suite existed with three test files and could not run:
# no WordPress test suite was installed, and the plugin's own bootstrap
# fataled on a fresh test database (the migrator creates canonical pages on
# plugins_loaded, where $wp_rewrite is still null). Both fixed; gating it
# here is what stops the tests rotting again, which is how they got into
# that state.
#
# WP_TESTS_DIR wins if exported. Otherwise try this plugin's own install,
# then the WP-CLI scaffold default. Absent entirely, warn rather than fail —
# same contract as WPCS and PHPStan above, so a fresh clone is not blocked
# on a test-suite install.
if [ -f phpunit.xml.dist ] || [ -f phpunit.xml ]; then
  if [ -x vendor/bin/phpunit ]; then
    # No suite exported: provision a throwaway one in Docker (bin/ci-test-db.sh),
    # so PHPUnit runs on any machine with Docker instead of being skipped.
    # Opt out with LISTORA_CI_NO_DOCKER=1.
    if [ -z "${WP_TESTS_DIR:-}" ] && [ "${LISTORA_CI_NO_DOCKER:-0}" != "1" ] && [ -f bin/ci-test-db.sh ]; then
      _provision_out="$(bash bin/ci-test-db.sh up)"
      _provision_rc=$?
      _provisioned="$(printf '%s\n' "$_provision_out" | tail -1)"
      if [ -n "$_provisioned" ]; then
        export WP_TESTS_DIR="$_provisioned"
      elif [ "$_provision_rc" -ne 2 ]; then
        # Docker was there and provisioning broke. Fail loudly: warning and
        # carrying on is how PHPUnit went unrun while CI reported green.
        # (Exit 2 = no Docker, which falls through to the skip warning.)
        run_stage "1.4" "PHPUnit (test DB provisioning failed - see ci-test-db output above)" false
        _phpunit_failed_provision=1
      fi
    fi
    if [ -z "${WP_TESTS_DIR:-}" ]; then
      for _candidate in /tmp/wb-listora-tests-lib /tmp/wordpress-tests-lib; do
        if [ -f "$_candidate/includes/functions.php" ]; then
          export WP_TESTS_DIR="$_candidate"
          break
        fi
      done
    fi
    if [ "${_phpunit_failed_provision:-0}" = "1" ]; then
      :
    elif [ -n "${WP_TESTS_DIR:-}" ] && [ -f "${WP_TESTS_DIR}/includes/functions.php" ]; then
      run_stage "1.4" "PHPUnit" vendor/bin/phpunit
    else
      warn "1.4 PHPUnit skipped — no WP test suite (start Docker, set WP_TESTS_DIR, or run bin/install-wp-tests.sh)"
    fi
  else
    warn "1.4 PHPUnit skipped — vendor/bin/phpunit not present"
  fi
fi

# ─── 2.x — Security + Architecture (always cheap) ────────────────────────────

# 2.0 — generated CSS must match its source. Covers the compiled
# variables/components sheets AND every blocks/*/style-rtl.css twin. The twins
# were hand-mirrored until 1.6.0 and drifted silently: an RTL favourite button
# stayed 36px after LTR moved to 44px, and kept a hardcoded white background
# after LTR moved to a dark-mode token. Nobody reported it because nobody
# browses the site in Arabic (BC 10208376041). A stale twin now fails here.
if [ -f bin/build-css.mjs ] && command -v node >/dev/null 2>&1; then
  run_stage "2.0" "Generated CSS in sync (incl. RTL twins)" node bin/build-css.mjs --check
fi

if [ -x bin/coding-rules-check.sh ]; then
  run_stage "2.1" "Coding-rules check" bash bin/coding-rules-check.sh
fi

if [ -x bin/architecture-checks.sh ]; then
  run_stage "2.2" "Architecture invariants (Free/Pro contract)" bash bin/architecture-checks.sh
fi

if [ -x bin/audit-guardrails.sh ]; then
  run_stage "2.3" "Audit guardrails (drift / boundary / gating)" bash bin/audit-guardrails.sh
fi

# 2.4 — Shape-fuzz smoke: renders customer surfaces with corrupted stored
# shapes (string options, scalar transients, junk filter returns). This is
# the gate PHPStan L7 cannot be — Field::get() returns mixed, so offset
# fatals on stored data are invisible to static analysis. Needs a live WP
# install; skipped (warn) when wp-cli or the install is unavailable.
if [ -f bin/shape-smoke.php ] && [ "$MODE" != "quick" ]; then
  WP_ROOT="$(cd "$(pwd)/../../.." && pwd)"
  if command -v wp > /dev/null 2>&1 && [ -f "$WP_ROOT/wp-load.php" ]; then
    run_stage "2.4" "Shape-fuzz smoke (corrupted stored shapes)" wp eval-file bin/shape-smoke.php --path="$WP_ROOT"
  else
    warn "2.4 Shape-fuzz smoke skipped — wp-cli or WP install not found"
  fi
fi

# 2.5 — Docs coverage: code -> docs. The drift direction (docs -> code) only
# asks whether a documented symbol still exists; it passes cleanly while a hook
# ships with no documentation at all, because there is no doc to be wrong. This
# is the other direction, and without it the docs gate is decorative.
if [ -f bin/docs-coverage-gate.py ] && [ "$MODE" != "quick" ]; then
  run_stage "2.5" "Docs coverage (hooks + REST routes vs docs)" python3 bin/docs-coverage-gate.py
fi

# ─── 3.x — Manifest freshness ────────────────────────────────────────────────

if [ "$MODE" != "quick" ]; then
  if [ -f audit/manifest.json ]; then
    if jq . audit/manifest.json > /dev/null 2>&1; then
      pass "3.1 Manifest is valid JSON"

      MANIFEST_AT="$(jq -r '.generated.at // empty' audit/manifest.json)"
      if [ -n "$MANIFEST_AT" ]; then
        # generated.at is a plain date (2026-09-01) or a full timestamp; read the
        # date part with BSD date, then GNU date. An unparseable value used to
        # fall back to 0 and report the manifest's age since 1970 (20713d).
        MANIFEST_DAY="${MANIFEST_AT:0:10}"
        MANIFEST_TS="$(date -juf "%Y-%m-%d" "$MANIFEST_DAY" +%s 2>/dev/null || date -u -d "$MANIFEST_DAY" +%s 2>/dev/null || true)"
        AGE_DAYS=-1
        [ -n "$MANIFEST_TS" ] && AGE_DAYS=$(( ($(date -u +%s) - MANIFEST_TS) / 86400 ))
        if [ "$AGE_DAYS" -lt 0 ]; then
          warn "3.1 Manifest generated.at '$MANIFEST_AT' is not a date"
        elif [ "$AGE_DAYS" -gt 30 ]; then
          warn "3.1 Manifest is ${AGE_DAYS}d old — refresh via /wp-plugin-onboard --refresh"
        fi
      fi
    else
      fail "3.1 Manifest JSON invalid"
    fi
  else
    warn "3.1 No audit/manifest.json — run /wp-plugin-onboard"
  fi
fi

# ─── 4.x — Journeys (browser-dependent, can be skipped) ──────────────────────

if [ "$MODE" = "full" ]; then
  if [ -d docs/qa/journeys ] && [ -x bin/run-journeys.sh ]; then
    if curl -fsS "$SITE_URL" > /dev/null 2>&1; then
      run_stage "4.1" "Customer journeys (browser+REST+DB)" bash bin/run-journeys.sh --site "$SITE_URL"
    else
      warn "4.1 Journeys skipped — site $SITE_URL is not reachable"
    fi
  fi
fi

# ─── Summary ─────────────────────────────────────────────────────────────────

echo ""
echo "=== Summary ==="
if [ ${#FAILED[@]} -eq 0 ]; then
  printf "${GREEN}local-CI green${RESET}\n"
  exit 0
else
  printf "${RED}local-CI failed: %d stage(s)${RESET}\n" "${#FAILED[@]}"
  for stage in "${FAILED[@]}"; do
    printf "  ${RED}✗${RESET} %s\n" "$stage"
  done
  exit 1
fi
