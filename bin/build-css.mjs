#!/usr/bin/env node
/**
 * WB Listora — CSS build (no dependencies).
 *
 * Concatenates the source @import manifests into the served stylesheets so
 * `src/` is the single source of truth. Run via `npm run build:css` (and
 * chained into `npm run build`).
 *
 *   src/variables/index.css   →  assets/css/listora-variables.css
 *   src/components/index.css  →  assets/css/listora-components.css
 *
 * Each manifest is a plain CSS file containing `@import "./leaf.css";` lines
 * (one level deep — leaves contain no further @imports). Imports are inlined
 * in order, each prefixed with a `/* === path === *​/` banner for readability.
 * Never hand-edit the generated files; edit the source + rebuild.
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const PLUGIN_DIR = resolve( dirname( fileURLToPath( import.meta.url ) ), '..' );

// `--check` verifies the committed compiled files match a fresh build (drift
// guard for CI) — it writes nothing and exits 1 on any mismatch.
const CHECK_ONLY = process.argv.includes( '--check' );

const TARGETS = [
	{
		manifest: 'src/variables/index.css',
		out: 'assets/css/listora-variables.css',
		title: 'WB Listora — design variables (compiled output)',
	},
	{
		manifest: 'src/components/index.css',
		out: 'assets/css/listora-components.css',
		title: 'WB Listora — UI components (compiled output)',
	},
];

const IMPORT_RE = /@import\s+["']([^"']+)["']\s*;/g;

/**
 * Resolve a manifest's @import list (in order) and inline each file's contents.
 *
 * @param {string} manifestAbs Absolute path to the index.css manifest.
 * @returns {string} Concatenated CSS.
 */
function inlineManifest( manifestAbs ) {
	const manifestDir = dirname( manifestAbs );
	const src = readFileSync( manifestAbs, 'utf8' );
	const parts = [];

	for ( const match of src.matchAll( IMPORT_RE ) ) {
		const importAbs = resolve( manifestDir, match[ 1 ] );
		const rel = relative( PLUGIN_DIR, importAbs );
		const body = readFileSync( importAbs, 'utf8' ).replace( /\s+$/, '' );
		parts.push( `/* === ${ rel } === */\n${ body }\n` );
	}

	return parts.join( '\n' );
}

function header( title ) {
	return (
		`/**\n` +
		` * ${ title }\n` +
		` *\n` +
		` * GENERATED by bin/build-css.mjs — do NOT edit directly.\n` +
		` * Edit the source files in src/ and run \`npm run build:css\`.\n` +
		` *\n` +
		` * @package WBListora\n` +
		` */\n\n`
	);
}

import { execFileSync } from 'node:child_process';

/**
 * Generate an `*-rtl.css` twin for a built LTR file via rtlcss.
 *
 * The compiled core CSS files contain direction-sensitive properties
 * (border-right, padding-left, etc.) that won't auto-flip on RTL sites.
 * WP serves `*-rtl.css` when `is_rtl()` is true via the wp_style_add_data
 * call in class-plugin.php::mark_styles_rtl(). Without these twins, RTL
 * sites silently fall back to LTR. Uses execFileSync (no shell) so the
 * paths can't be misinterpreted as shell tokens.
 */
function generateRtl( ltrAbs ) {
	const rtlAbs = ltrAbs.replace( /\.css$/, '-rtl.css' );
	const rtlcssBin = resolve( PLUGIN_DIR, 'node_modules/.bin/rtlcss' );
	if ( ! existsSync( rtlcssBin ) ) {
		return null;
	}
	execFileSync( rtlcssBin, [ ltrAbs, rtlAbs ], { stdio: 'pipe' } );
	return rtlAbs;
}

let failed = false;
for ( const t of TARGETS ) {
	const manifestAbs = resolve( PLUGIN_DIR, t.manifest );
	const outAbs = resolve( PLUGIN_DIR, t.out );
	try {
		const css = header( t.title ) + inlineManifest( manifestAbs ) + '\n';
		if ( CHECK_ONLY ) {
			const existing = existsSync( outAbs ) ? readFileSync( outAbs, 'utf8' ) : '';
			if ( existing !== css ) {
				failed = true;
				// eslint-disable-next-line no-console
				console.error( `✗ ${ t.out } is out of sync with ${ t.manifest } — run \`npm run build:css\` and commit.` );
			} else {
				// eslint-disable-next-line no-console
				console.log( `✓ ${ t.out } in sync with ${ t.manifest }` );
			}
		} else {
			writeFileSync( outAbs, css );
			// eslint-disable-next-line no-console
			console.log( `✓ ${ t.out }  (from ${ t.manifest })` );
			try {
				const rtlOut = generateRtl( outAbs );
				if ( rtlOut ) {
					// eslint-disable-next-line no-console
					console.log( `✓ ${ relative( PLUGIN_DIR, rtlOut ) }  (RTL twin)` );
				}
			} catch ( e ) {
				// eslint-disable-next-line no-console
				console.warn( `⚠ RTL twin for ${ t.out } failed: ${ e.message }` );
			}
		}
	} catch ( err ) {
		failed = true;
		// eslint-disable-next-line no-console
		console.error( `✗ ${ t.out }: ${ err.message }` );
	}
}

process.exit( failed ? 1 : 0 );
